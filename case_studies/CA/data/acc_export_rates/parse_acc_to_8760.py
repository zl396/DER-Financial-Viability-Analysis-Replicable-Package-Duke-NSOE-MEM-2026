def generate_2026_hours():
    """Generate all 8760 hours of 2026 in Pacific prevailing time."""
    # 2026 DST: Mar 8 2:00 AM -> 3:00 AM (spring forward)
    #           Nov 1 2:00 AM -> 1:00 AM (fall back)
    # For simplicity, use pandas with timezone
    start = pd.Timestamp("2026-01-01", tz="America/Los_Angeles")
    end = pd.Timestamp("2027-01-01", tz="America/Los_Angeles")
    hours = pd.date_range(start, end, freq="h", inclusive="left")
    return hours


def get_day_type(dt):
    """Return 'Weekday' or 'Weekend' based on date (holidays count as weekend)."""
    d = dt.date() if hasattr(dt, 'date') else dt
    if isinstance(d, pd.Timestamp):
        d = d.date()
    naive_dt = datetime(d.year, d.month, d.day)
    if naive_dt in FEDERAL_HOLIDAYS_2026:
        return "Weekend"
    if d.weekday() >= 5:  # Saturday=5, Sunday=6
        return "Weekend"
    return "Weekday"


