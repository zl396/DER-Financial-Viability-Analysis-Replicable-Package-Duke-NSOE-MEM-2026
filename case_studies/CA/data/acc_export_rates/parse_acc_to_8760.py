# =====================================================================
# SCE & SDG&E: Parse from MIDAS CSV files
# =====================================================================
def parse_midas_csv(csv_path, gen_prefix, del_prefix, rate_name, utility_name):
    """Parse a MIDAS format CSV into 8760 hourly export rates.

    Args:
        csv_path: Path to the MIDAS CSV
        gen_prefix: RIN prefix for generation rates (e.g., 'USCA-XXSC')
        del_prefix: RIN prefix for delivery rates (e.g., 'USCA-SCXX')
        rate_name: RateName filter (e.g., 'NBT26')
        utility_name: For output filename
    """
    with open(csv_path, encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    # Build lookup: (month_abbr, day_type, hour) -> (gen_rate, del_rate)
    # ValueName format: "Jan Weekday HS0", "Jan Weekend HS0", etc.
    # IMPORTANT: Filter to 2026 dates only! The MIDAS files contain 20 years
    # of forecasted rates, and later years have different values.
    lookup_gen = {}
    lookup_del = {}

    for r in rows:
        if r["RateName"] != rate_name:
            continue
        # Only use 2026 data (first year)
        if "/2026" not in r["DateStart"]:
            continue
        vname = r["ValueName"]  # e.g., "Jan Weekday HS0"
        parts = vname.split()
        if len(parts) != 3:
            continue
        month_abbr = parts[0]
        day_type = parts[1]  # "Weekday" or "Weekend"
        hour = int(parts[2].replace("HS", ""))
        key = (month_abbr, day_type, hour)
        val = float(r["Value"])

        if gen_prefix in r["RIN"]:
            lookup_gen[key] = val
        elif del_prefix in r["RIN"]:
            lookup_del[key] = val

    print(f"{utility_name}: {len(lookup_gen)} gen entries, {len(lookup_del)} del entries")

    # Expand to 8760
    hours = generate_2026_hours()
    records = []
    for ts in hours:
        month_abbr = MONTH_ABBR[ts.month]
        h = ts.hour
        day_type = get_day_type(ts)
        key = (month_abbr, day_type, h)

        gen_rate = lookup_gen.get(key, 0.0)
        del_rate = lookup_del.get(key, 0.0)
        total = gen_rate + del_rate

        records.append({
            "datetime_local": ts.strftime("%Y-%m-%d %H:%M"),
            "month": ts.month,
            "hour": h,
            "day_type": day_type,
            "export_rate_kwh": round(total, 6),
        })

    df = pd.DataFrame(records)
    outpath = OUTPUT_DIR / f"{utility_name.lower()}_acc_export_8760_2026.csv"
    df.to_csv(outpath, index=False)
    print(f"  {len(df)} rows -> {outpath}")
    print(f"  Annual avg: ${df['export_rate_kwh'].mean():.5f}/kWh")
    print(f"  Min: ${df['export_rate_kwh'].min():.5f}  Max: ${df['export_rate_kwh'].max():.5f}")
    return df


